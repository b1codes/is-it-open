// Visual regression tests: every catalog use case, in light and dark, at
// phone, tablet and desktop widths, at text scale 1.0 and 2.0, compared
// pixel for pixel against the PNGs under test/goldens/.
//
// Screens are captured at the full viewport. Components on a ComponentStage,
// and component dialogs, are cropped to the component (plus a margin for
// shadows), since the rest is the stage's backdrop; the crop is taken from
// the full render, so glass blur still samples the real backdrop.
//
// Font rasterization differs between operating systems (and between Flutter
// engine versions), so the goldens are generated by the Goldens CI job on a
// pinned runner and Flutter version, and only compared on Linux. Elsewhere
// these tests are skipped. To update them, see "Visual regression" in
// TESTING.md.

/// A Wednesday mid-morning, outside any DST change, so opening hours, the
/// calendar and today's route render the same on every run.
final _now = DateTime(2026, 6, 10, 10, 30);

class _Device {
  const _Device(this.name, this.size, {this.padding = FakeViewPadding.zero});

  final String name;
  final Size size;

  /// Safe-area insets (notch and home indicator).
  final FakeViewPadding padding;
}

// Phone and tablet match the catalog's iPhone 13 and iPad Pro 11" viewports.
const _devices = [
  _Device(
    'phone',
    Size(390, 844),
    padding: FakeViewPadding(top: 47, bottom: 34),
  ),
  _Device(
    'tablet',
    Size(834, 1194),
    padding: FakeViewPadding(top: 24, bottom: 20),
  ),
  _Device('desktop', Size(1280, 800)),
];

const _themes = ['Light', 'Dark'];
const _textScales = [1.0, 2.0];

/// Layout overflows the goldens currently show (as yellow-and-black stripes),
/// by use case and the source location of the widget that overflows. Tracked
/// in https://github.com/b1codes/is-it-open/issues/47.
///
/// A listed overflow doesn't fail its test; any other overflow does. A listed
/// one that no longer happens anywhere in its use case's matrix fails too, so
/// remove it from here once it's fixed (and update the goldens).
const _knownOverflows = <String, Set<String>>{
  'components/calendar/plannerview/default': {
    'lib/components/calendar/planner_view.dart:305',
  },
  'components/places/savedplacetile/default': {
    'lib/components/places/saved_place_tile.dart:50',
  },
  'components/places/savedplacetile/grid': {
    'lib/components/places/saved_place_tile.dart:50',
  },
  'components/shared/auth0universallogindialog/default': {
    'lib/components/shared/auth0_universal_login_dialog.dart:336',
    'lib/components/shared/auth0_universal_login_dialog.dart:395',
  },
  'screens/auth/loginscreen/default': _loginScreenOverflows,
  'screens/auth/loginscreen/signing-in': _loginScreenOverflows,
  'screens/auth/registerscreen/default': {
    'lib/screens/auth/register_screen.dart:155',
  },
  'screens/auth/registerscreen/creating-account': {
    'lib/screens/auth/register_screen.dart:155',
  },
  'screens/home/homescreen/signed-in': {
    'lib/screens/home/home_screen.dart:135',
  },
  'screens/places/myplacesscreen/empty': {
    'lib/screens/places/my_places_screen.dart:1225',
  },
};

const _loginScreenOverflows = {
  'lib/screens/auth/login_screen.dart:237',
  'lib/screens/auth/login_screen.dart:284',
  'lib/screens/auth/login_screen.dart:309',
};

/// `light-phone-2x`.
String _caseName(String theme, _Device device, double scale) =>
    '${theme.toLowerCase()}-${device.name}-${scale.toInt()}x';

/// `goldens/screens/places/placedetailscreen/on-todays-route/light-phone-2x.png`
/// for the use case `screens/places/placedetailscreen/on-today's-route`,
/// relative to test/.
String _goldenPath(String path, String caseName) =>
    'goldens/${path.replaceAll(RegExp(r'[^a-z0-9/-]'), '')}/$caseName.png';

/// `lib/components/calendar/planner_view.dart:305` for an overflow reported
/// on a widget created at that line of the app (or the catalog).
String? _overflowLocation(FlutterErrorDetails details) {
  if (!details.exceptionAsString().contains('overflowed by')) return null;
  final match = RegExp(
    r'file://\S*?/frontend/((?:widgetbook/)?lib/[^:\s]+:\d+)',
  ).firstMatch(details.toString());
  return match?.group(1) ?? 'unknown location';
}

void main() {
  final skip = Platform.isLinux
      ? null
      : 'Goldens are rendered on Linux CI; see "Visual regression" in '
            'TESTING.md.';

  if (goldenFileComparator case final LocalFileComparator local) {
    goldenFileComparator = _Comparator(
      local.basedir.resolve('goldens_test.dart'),
    );
  }

  setUpAll(() {
    // setUpAll runs even when every test is skipped.
    if (skip != null) return;
    // DateTime(...) above is local time, so the zone decides which instant
    // "now" is. The CI job and `make test-goldens` set TZ=UTC.
    expect(
      _now.timeZoneOffset,
      Duration.zero,
      reason: 'Run the golden tests with TZ=UTC.',
    );
  });

  test('every golden belongs to a use case', () {
    final expected = {
      for (final path in useCasePaths)
        for (final theme in _themes)
          for (final device in _devices)
            for (final scale in _textScales)
              _goldenPath(path, _caseName(theme, device, scale)),
    };
    final dir = Directory('test/goldens');
    final orphans = [
      if (dir.existsSync())
        for (final file in dir.listSync(recursive: true).whereType<File>())
          file.path.substring('test/'.length),
    ].where((golden) => !expected.contains(golden)).toList()..sort();
    expect(
      orphans,
      isEmpty,
      reason: 'No use case renders these; delete them (or regenerate).',
    );
  }, skip: skip);

  for (final path in useCasePaths) {
    group(path, () {
      final known = _knownOverflows[path] ?? const {};
      final seen = <String>{};
      var ran = 0;

      for (final theme in _themes) {
        for (final device in _devices) {
          for (final scale in _textScales) {
            final name = _caseName(theme, device, scale);
            testWidgets(name, (tester) async {
              ran++;
              tester.view
                ..physicalSize = device.size
                ..devicePixelRatio = 1
                ..padding = device.padding
                ..viewPadding = device.padding;
              addTearDown(tester.view.reset);

              final onError = FlutterError.onError;
              FlutterError.onError = (details) {
                final location = _overflowLocation(details);
                if (location != null && known.contains(location)) {
                  seen.add(location);
                } else {
                  onError?.call(details);
                }
              };
              addTearDown(() => FlutterError.onError = onError);

              await withClock(Clock.fixed(_now), () async {
                await pumpUseCase(tester, path, theme: theme, textScale: scale);
                // A text style that asks for a font variant that isn't
                // bundled fails here, instead of rendering a fallback.
                await tester.runAsync(GoogleFonts.pendingFonts);
                await tester.pump();
                FlutterError.onError = onError;

                final image = await _capture(
                  tester,
                  device.size,
                  isComponent: path.startsWith('components/'),
                );
                await expectLater(
                  image,
                  matchesGoldenFile(_goldenPath(path, name)),
                );
                await unmountUseCase(tester);
              });
            });
          }
        }
      }

      tearDownAll(() {
        // Only meaningful when the whole matrix ran (not under --name).
        if (ran < _themes.length * _devices.length * _textScales.length) {
          return;
        }
        final fixed = known.difference(seen);
        expect(
          fixed,
          isEmpty,
          reason:
              'These no longer overflow in $path; remove them from '
              '_knownOverflows.',
        );
      });
    }, skip: skip);
  }
}

/// The whole view, or for a component, its bounds plus a margin.
Future<ui.Image> _capture(
  WidgetTester tester,
  Size viewSize, {
  required bool isComponent,
}) async {
  final root = find.byType(WidgetbookApp).evaluate().single;
  final subject = isComponent ? _componentSubject() : null;
  final crop = subject == null
      ? null
      : _pixelRect(tester.getRect(subject).inflate(16), viewSize);

  return (await tester.runAsync(() async {
    final full = await captureImage(root);
    if (crop == null) return full;
    final recorder = ui.PictureRecorder();
    Canvas(recorder).drawImageRect(
      full,
      crop,
      Offset.zero & crop.size,
      Paint()..filterQuality = FilterQuality.none,
    );
    final picture = recorder.endRecording();
    final cropped = await picture.toImage(
      crop.width.toInt(),
      crop.height.toInt(),
    );
    picture.dispose();
    full.dispose();
    return cropped;
  }))!;
}

/// The staged component, or the surface of a dialog component; null when
/// the component fills the view.
Finder? _componentSubject() {
  final staged = find.byKey(ComponentStage.subjectKey);
  if (staged.evaluate().length == 1) return staged;
  final dialog = find.descendant(
    of: find.byType(Dialog),
    matching: find.byType(Material),
  );
  if (dialog.evaluate().isNotEmpty) return dialog.first;
  return null;
}

/// [rect] snapped outward to whole pixels and clipped to the view.
Rect _pixelRect(Rect rect, Size viewSize) => Rect.fromLTRB(
  rect.left.floorToDouble().clamp(0, viewSize.width),
  rect.top.floorToDouble().clamp(0, viewSize.height),
  rect.right.ceilToDouble().clamp(0, viewSize.width),
  rect.bottom.ceilToDouble().clamp(0, viewSize.height),
);

/// Writes failure images under test/failures/ at the golden's own path
/// (`failures/goldens/<use case>/light-phone-1x_isolatedDiff.png`). The
/// default names them by file name alone, so every use case's
/// `light-phone-1x` failure would overwrite the last one.
class _Comparator extends LocalFileComparator {
  _Comparator(super.testFile);

  @override
  File getFailureFile(String failure, Uri golden, Uri basedir) {
    final name = golden.path.replaceFirst(RegExp(r'\.png$'), '');
    return File.fromUri(basedir.resolve('failures/${name}_$failure.png'));
  }
}
