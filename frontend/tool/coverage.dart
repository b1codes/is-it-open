// Coverage helpers for CI and `make coverage-frontend`.
//
//   dart run tool/coverage.dart imports
//       Writes test/coverage_imports_test.dart, which imports every library under lib/ so that
//       files no test touches still show up in lcov.info (at 0%) instead of being left out.
//
//   dart run tool/coverage.dart check [--min=<percent>] [--lcov=coverage/lcov.info]
//       Prints line coverage per file and in total, appends the table to $GITHUB_STEP_SUMMARY
//       when set, and exits 1 if the total is below --min.
import 'dart:io';

const _importsTest = 'test/coverage_imports_test.dart';

void main(List<String> args) {
  if (args.isEmpty) _usage();
  switch (args.first) {
    case 'imports':
      _writeImports();
    case 'check':
      final options = {
        for (final arg in args.skip(1))
          if (arg.startsWith('--') && arg.contains('='))
            arg.substring(2, arg.indexOf('=')): arg.substring(
              arg.indexOf('=') + 1,
            ),
      };
      _check(
        options['lcov'] ?? 'coverage/lcov.info',
        double.parse(options['min'] ?? '0'),
      );
    default:
      _usage();
  }
}

Never _usage() {
  stderr.writeln(
    'usage: dart run tool/coverage.dart imports | check [--min=<percent>] [--lcov=<path>]',
  );
  exit(64);
}

void _writeImports() {
  final package = RegExp(
    r'^name:\s*(\S+)',
    multiLine: true,
  ).firstMatch(File('pubspec.yaml').readAsStringSync())!.group(1);
  final libraries =
      Directory('lib')
          .listSync(recursive: true)
          .whereType<File>()
          .map((f) => f.path.replaceAll(r'\', '/'))
          .where(
            (p) =>
                p.endsWith('.dart') &&
                !p.endsWith('.g.dart') &&
                !p.endsWith('.mocks.dart'),
          )
          .map((p) => p.substring('lib/'.length))
          .toList()
        ..sort();
  File(_importsTest).writeAsStringSync(
    [
      '// GENERATED by tool/coverage.dart; do not edit or commit.',
      '// ignore_for_file: unused_import',
      for (final lib in libraries) "import 'package:$package/$lib';",
      '',
      'void main() {}',
      '',
    ].join('\n'),
  );
  stdout.writeln('Wrote $_importsTest (${libraries.length} libraries).');
}

void _check(String lcovPath, double min) {
  final lcov = File(lcovPath);
  if (!lcov.existsSync()) {
    stderr.writeln('$lcovPath not found; run `flutter test --coverage` first.');
    exit(1);
  }
  final hits = <String, (int found, int hit)>{};
  String? file;
  var found = 0, hit = 0;
  for (final line in lcov.readAsLinesSync()) {
    if (line.startsWith('SF:')) {
      file = line.substring(3);
      found = hit = 0;
    } else if (line.startsWith('DA:')) {
      found++;
      if (int.parse(line.split(',')[1]) > 0) hit++;
    } else if (line == 'end_of_record' && file != null) {
      hits[file] = (found, hit);
      file = null;
    }
  }

  final files = hits.keys.toList()
    ..sort((a, b) => _pct(hits[a]!).compareTo(_pct(hits[b]!)));
  final totalFound = hits.values.fold(0, (sum, v) => sum + v.$1);
  final totalHit = hits.values.fold(0, (sum, v) => sum + v.$2);
  final total = totalFound == 0 ? 100.0 : 100 * totalHit / totalFound;
  final passed = total + 1e-9 >= min;

  final rows = [
    '| File | Lines | Covered |',
    '| --- | ---: | ---: |',
    for (final f in files)
      '| `$f` | ${hits[f]!.$1} | ${_pct(hits[f]!).toStringAsFixed(1)}% |',
    '| **Total** | **$totalFound** | **${total.toStringAsFixed(1)}%** |',
  ];
  stdout.writeln(rows.join('\n'));
  final verdict = passed
      ? 'Frontend line coverage ${total.toStringAsFixed(2)}% meets the ${min.toStringAsFixed(0)}% minimum.'
      : 'Frontend line coverage ${total.toStringAsFixed(2)}% is below the ${min.toStringAsFixed(0)}% minimum.';
  stdout.writeln('\n$verdict');

  final summary = Platform.environment['GITHUB_STEP_SUMMARY'];
  if (summary != null && summary.isNotEmpty) {
    File(summary).writeAsStringSync(
      '## Frontend coverage\n\n$verdict\n\n<details><summary>Per-file coverage</summary>\n\n${rows.join('\n')}\n\n</details>\n',
      mode: FileMode.append,
    );
  }
  if (!passed) exit(1);
}

double _pct((int, int) v) => v.$1 == 0 ? 100 : 100 * v.$2 / v.$1;
